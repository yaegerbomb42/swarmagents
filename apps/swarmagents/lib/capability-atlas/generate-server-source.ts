/**
 * Generate the embedded atlas MCP server source.
 *
 * The in-VM query server must run with node builtins only (no npm install
 * inside the VM), so its program is bundled into a single self-contained
 * script and checked in as `lib/harness/atlas-mcp-source.ts`. This module
 * performs that bundling using the TypeScript compiler (a devDependency)
 * to strip types, then concatenates the results and refuses any import
 * outside the closed set below — so a future dependency added to the
 * retrieval code fails loudly here instead of shipping a broken server
 * into the VM. No bundler dependency is needed: the retrieval modules
 * have no runtime imports outside this set.
 *
 * Run: `npm run generate:atlas-server` (from apps/swarmagents/).
 * The atlas test suite asserts the checked-in file matches this output.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const HERE = path.dirname(fileURLToPath(import.meta.url));

/** Sources concatenated in dependency order (entry last: it runs at load). */
const SOURCES = [
  "retrieval/bm25.ts",
  "retrieval/embeddings.ts",
  "retrieval/index.ts",
  "server-entry.ts",
] as const;

/** Relative import sources that resolve inside this closed set (dropped). */
const LOCAL_SOURCES = new Set([
  "./bm25",
  "./embeddings",
  "./schema",
  "./index",
  "../schema",
  "../retrieval/index",
  "./retrieval/index",
]);

const IMPORT_RE = /^\s*import\s+(.+?)\s+from\s+['"]([^'"]+)['"];?\s*$/;
const VALUE_EXPORT_RE = /^\s*export\s+(default\s+)?(class|function|const|let|var|async\s+function)\b/;

/**
 * Transpile one TS source to JS (types stripped), then drop module syntax
 * for the concatenation: local imports are dropped (their targets are
 * concatenated into the same script), node: imports are kept, and anything
 * else throws, so the bundle can never silently gain a runtime dependency.
 */
function bundleSource(fileName: string, text: string): string[] {
  const transpiled = ts.transpileModule(text, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
    fileName,
  }).outputText;
  const out: string[] = [];
  for (const line of transpiled.split("\n")) {
    if (/^\s*export\s*\{\s*\}\s*;?\s*$/.test(line)) continue;
    const importMatch = IMPORT_RE.exec(line);
    if (importMatch) {
      const source = importMatch[2]!;
      if (source.startsWith("node:")) {
        out.push(line);
        continue;
      }
      if (LOCAL_SOURCES.has(source)) continue;
      throw new Error(`${fileName}: unsupported import source "${source}"`);
    }
    if (/^\s*import\b/.test(line)) {
      throw new Error(`${fileName}: unsupported import statement: ${line.trim()}`);
    }
    const valueExport = VALUE_EXPORT_RE.exec(line);
    if (valueExport) {
      out.push(line.replace(/^\s*export\s+/, ""));
      continue;
    }
    if (/^\s*export\b/.test(line)) {
      throw new Error(`${fileName}: unsupported export statement: ${line.trim()}`);
    }
    out.push(line);
  }
  return out;
}

const HEADER = `/**
 * The capability-atlas MCP server (GENERATED — do not edit by hand).
 *
 * Generated by \`npm run generate:atlas-server\` from
 * lib/capability-atlas/server-entry.ts + lib/capability-atlas/retrieval/*.
 * The server is written into the user's VM next to the role-switch server
 * and exposed to the agent as the \`capability-atlas\` MCP server. It reads
 * the registry JSON published in the VM ($HOME/.swarm/atlas/registry.json,
 * or SWARM_ATLAS_REGISTRY when set) and serves find_capability /
 * describe_capability over it. Node builtins only; registry entries are
 * shape-checked and projected to scalar fields, so no secret value can
 * ever be served.
 */

/** Name of the stdio MCP server exposing find_capability/describe_capability. */
export const ATLAS_MCP_SERVER_NAME = "capability-atlas";

/** Path (inside the VM) the server is written to. */
export const ATLAS_MCP_SERVER_PATH = "/workspace/.swarm/atlas-server.mjs";

/** The tool the agent calls to find capabilities. */
export const ATLAS_FIND_TOOL = "find_capability";

/** The tool the agent calls to describe one capability. */
export const ATLAS_DESCRIBE_TOOL = "describe_capability";
`;

/** Build the full text of `lib/harness/atlas-mcp-source.ts`. Deterministic. */
export function buildAtlasServerSource(rootDir: string = HERE): string {
  const program: string[] = [];
  for (const rel of SOURCES) {
    const filePath = path.join(rootDir, rel);
    const text = fs.readFileSync(filePath, "utf8");
    program.push(...bundleSource(rel, text));
  }
  // The concatenated program must contain no leftover module syntax and
  // no TypeScript-only syntax (a stray annotation means transpilation
  // did not run or a new construct slipped through).
  for (const line of program) {
    if (/^\s*import\s/.test(line) && !line.includes("node:")) {
      throw new Error(`bundled program still has a non-node import: ${line.trim()}`);
    }
    if (/^\s*export\s/.test(line)) {
      throw new Error(`bundled program still has an export: ${line.trim()}`);
    }
    if (/: string\b|: number\b|: boolean\b/.test(line) && /function |const .* =|=>/.test(line)) {
      throw new Error(`bundled program still has type syntax: ${line.trim()}`);
    }
  }
  const body = program.map((line) => `    ${JSON.stringify(line)},`).join("\n");
  return (
    `${HEADER}\n` +
    `/** The server program, written verbatim into the VM. */\n` +
    `export function atlasMcpServerSource(): string {\n` +
    `  return [\n${body}\n  ].join("\\n");\n}\n`
  );
}

const __filename = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  const outPath = path.join(HERE, "..", "harness", "atlas-mcp-source.ts");
  const text = buildAtlasServerSource();
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, text, "utf8");
  console.log(`wrote ${outPath} (${text.length} bytes)`);
}
