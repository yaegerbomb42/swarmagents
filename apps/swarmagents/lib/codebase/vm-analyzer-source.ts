/**
 * The codebase scanner that runs *inside the user's VM*.
 *
 * The repository lives in the VM, not on the app server, so the scan has to
 * happen there. This module generates the program that does it: a small,
 * dependency-free Node script that walks the repository, reads the files it
 * needs, asks git for the churn of the last 90 days and prints one JSON
 * document (a `CodebaseScan`) on stdout.
 *
 * Every rule it applies comes from lib/codebase/rules.ts, so the VM and the
 * server can never drift apart on what counts as source, an import or an
 * export. The server then does all the ranking, budgeting and wording.
 */

import {
  DYNAMIC_IMPORT_RE,
  EXPORT_PATTERNS,
  EXT_LANG,
  GO_EXPORT_RE,
  IGNORE_DIRS,
  IGNORE_FILES,
  MAX_IMPORTS_PER_FILE,
  MAX_PARSED_FILE_BYTES,
  MAX_SCANNED_FILES,
  PYTHON_EXPORT_RE,
  PYTHON_IMPORT_RE,
  REQUIRE_RE,
  RUST_EXPORT_RE,
  SOURCE_EXTS,
  STATIC_IMPORT_RE,
} from "./rules";

/** Where the analyzer is written inside the user's VM. */
export const CODEBASE_ANALYZER_PATH = "/workspace/.swarm/codebase-analyzer.mjs";

function regexLiteral(re: RegExp): string {
  return `new RegExp(${JSON.stringify(re.source)}, ${JSON.stringify(re.flags)})`;
}

/** The scanner program, written verbatim into the VM. */
export function codebaseAnalyzerSource(): string {
  const lines: string[] = [
    "#!/usr/bin/env node",
    "// SwarmAgents codebase scanner (auto-generated). Runs inside the user's VM.",
    "import fs from 'node:fs';",
    "import path from 'node:path';",
    "import crypto from 'node:crypto';",
    "import { execFileSync } from 'node:child_process';",
    "",
    `const EXT_LANG = ${JSON.stringify(EXT_LANG)};`,
    `const IGNORE_DIRS = new Set(${JSON.stringify(IGNORE_DIRS)});`,
    `const LOCK_FILES = new Set(['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lockb', 'bun.lock', 'Cargo.lock', 'poetry.lock', 'composer.lock']);`,
    `const IGNORE_FILES = new Set(${JSON.stringify(IGNORE_FILES)});`,
    `const SOURCE_EXTS = new Set(${JSON.stringify(SOURCE_EXTS)});`,
    `const JS_EXTS = new Set(['.ts', '.tsx', '.js', '.jsx', '.mts', '.cts', '.mjs', '.cjs']);`,
    `const MAX_PARSED_FILE_BYTES = ${MAX_PARSED_FILE_BYTES};`,
    `const MAX_SCANNED_FILES = ${MAX_SCANNED_FILES};`,
    `const MAX_IMPORTS_PER_FILE = ${MAX_IMPORTS_PER_FILE};`,
    `const STATIC_IMPORT_RE = new RegExp(${regexLiteral(STATIC_IMPORT_RE)});`,
    `const REQUIRE_RE = new RegExp(${regexLiteral(REQUIRE_RE)});`,
    `const DYNAMIC_IMPORT_RE = new RegExp(${regexLiteral(DYNAMIC_IMPORT_RE)});`,
    `const PYTHON_IMPORT_RE = new RegExp(${regexLiteral(PYTHON_IMPORT_RE)});`,
    `const PYTHON_EXPORT_RE = new RegExp(${regexLiteral(PYTHON_EXPORT_RE)});`,
    `const GO_EXPORT_RE = new RegExp(${regexLiteral(GO_EXPORT_RE)});`,
    `const RUST_EXPORT_RE = new RegExp(${regexLiteral(RUST_EXPORT_RE)});`,
    `const EXPORT_PATTERNS = ${JSON.stringify(EXPORT_PATTERNS.map((p) => ({ re: { source: p.re.source, flags: p.re.flags }, kind: p.kind })))};`,    "",
    "function repoHash(root) {",
    "  return crypto.createHash('sha1').update(path.resolve(root)).digest('hex').slice(0, 16);",
    "}",
    "",
    "function walk(root) {",
    "  const files = [];",
    "  const lockFiles = [];",
    "  let truncated = false;",
    "  const stack = [''];",
    "  while (stack.length) {",
    "    const rel = stack.pop();",
    "    let entries;",
    "    try {",
    "      entries = fs.readdirSync(path.join(root, rel), { withFileTypes: true });",
    "    } catch (err) {",
    "      continue;",
    "    }",
    "    for (const entry of entries) {",
    "      const childRel = rel ? rel + '/' + entry.name : entry.name;",
    "      if (entry.isDirectory()) {",
    "        if (IGNORE_DIRS.has(entry.name)) continue;",
    "        if (entry.name.startsWith('.')) continue;",
    "        stack.push(childRel);",
    "        continue;",
    "      }",
    "      if (!entry.isFile()) continue;",
    "      if (LOCK_FILES.has(entry.name)) { lockFiles.push(entry.name); continue; }",
    "      if (IGNORE_FILES.has(entry.name)) continue;",
    "      if (entry.name.startsWith('.') && entry.name !== '.env.example') continue;",
    "      files.push(childRel);",
    "      if (files.length >= MAX_SCANNED_FILES) { truncated = true; stack.length = 0; break; }",
    "    }",
    "  }",
    "  files.sort();",
    "  return { files, lockFiles, truncated };",
    "}",
    "",
    "function countLines(text) {",
    "  if (!text) return 0;",
    "  let n = 1;",
    "  for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) === 10) n++;",
    "  return n;",
    "}",
    "",
    "function looksBinary(text) {",
    "  const limit = Math.min(text.length, 8000);",
    "  for (let i = 0; i < limit; i++) if (text.charCodeAt(i) === 0) return true;",
    "  return false;",
    "}",
    "",
    "function countComplexity(content) {",
    "  // Branch-count complexity: how many branching constructs the file",
    "  // contains (if/for/while/switch/case/catch, ternary ?, &&, ||, ??).",
    "  // Comments and string/template literals are stripped first so a",
    "  // branchy word in a message cannot inflate the count. Hand-rolled",
    "  // state machine: regexes cannot tell a quote inside a comment from",
    "  // a real string. Template interpolations are skipped wholesale, so",
    "  // branches inside ${ ... } are missed; this is a heuristic, not a",
    "  // parser, and the number is only ever shown as 'complexity'.",
    "  let code = '';",
    "  let i = 0;",
    "  const n = content.length;",
    "  let state = 'code';",
    "  while (i < n) {",
    "    const ch = content[i];",
    "    const next = i + 1 < n ? content[i + 1] : '';",
    "    if (state === 'code') {",
    "      if (ch === '/' && next === '/') { state = 'line'; i += 2; continue; }",
    "      if (ch === '/' && next === '*') { state = 'block'; i += 2; continue; }",
    "      if (ch === \"'\") { state = 'sq'; i++; continue; }",
    "      if (ch === '\"') { state = 'dq'; i++; continue; }",
    "      if (ch === '`') { state = 'tpl'; i++; continue; }",
    "      code += ch; i++; continue;",
    "    }",
    "    if (state === 'line') { if (ch === '\\n') { state = 'code'; code += ch; } i++; continue; }",
    "    if (state === 'block') { if (ch === '*' && next === '/') { state = 'code'; i += 2; continue; } i++; continue; }",
    "    if (state === 'sq' || state === 'dq') {",
    "      const q = state === 'sq' ? \"'\" : '\"';",
    "      if (ch === '\\\\') { i += 2; continue; }",
    "      if (ch === q) { state = 'code'; i++; continue; }",
    "      if (ch === '\\n') { state = 'code'; i++; continue; }",
    "      i++; continue;",
    "    }",
    "    if (ch === '\\\\') { i += 2; continue; }",
    "    if (ch === '`') { state = 'code'; i++; continue; }",
    "    i++; continue;",
    "  }",
    "  let count = 0;",
    "  const keywords = code.match(/\\b(if|for|while|switch|case|catch)\\b/g);",
    "  if (keywords) count += keywords.length;",
    "  const ands = code.match(/&&/g);",
    "  if (ands) count += ands.length;",
    "  const ors = code.match(/\\|\\|/g);",
    "  if (ors) count += ors.length;",
    "  const nullish = code.match(/\\?\\?/g);",
    "  if (nullish) count += nullish.length;",
    "  const withoutNullish = code.replace(/\\?\\?/g, '  ');",
    "  const ternary = withoutNullish.match(/\\?(?![.?])/g);",
    "  if (ternary) count += ternary.length;",
    "  return count;",
    "}",
    "",
    "function readCoverage(root) {",
    "  // Per-file lines-covered percent, from a coverage artifact the repo",
    "  // already has. No test suite is ever run to produce one: when neither",
    "  // artifact exists the result is empty, and that is a normal state.",
    "  const out = {};",
    "  try {",
    "    const data = JSON.parse(fs.readFileSync(path.join(root, 'coverage', 'coverage-summary.json'), 'utf8'));",
    "    for (const key of Object.keys(data)) {",
    "      if (key === 'total') continue;",
    "      const pct = data[key] && data[key].lines && data[key].lines.pct;",
    "      if (typeof pct === 'number' && Number.isFinite(pct)) out[key] = Math.max(0, Math.min(100, pct));",
    "    }",
    "    if (Object.keys(out).length) return out;",
    "  } catch (err) { /* no usable summary: try coverage-final below */ }",
    "  try {",
    "    const data = JSON.parse(fs.readFileSync(path.join(root, 'coverage', 'coverage-final.json'), 'utf8'));",
    "    for (const key of Object.keys(data)) {",
    "      const s = data[key] && data[key].s;",
    "      if (!s || typeof s !== 'object') continue;",
    "      const hits = Object.values(s);",
    "      if (!hits.length) continue;",
    "      let covered = 0;",
    "      for (const h of hits) if (typeof h === 'number' && h > 0) covered++;",
    "      out[key] = (covered / hits.length) * 100;",
    "    }",
    "  } catch (err) { /* no coverage artifact: normal, not an error */ }",
    "  return out;",
    "}",
    "",
    "function addName(names, value) {",
    "  if (!value) return;",
    "  const name = String(value).trim();",
    "  if (!name || name === 'default' || name.length > 80) return;",
    "  names.add(name);",
    "}",
    "",
    "function extractExports(content, ext) {",
    "  const names = new Set();",
    "  if (JS_EXTS.has(ext)) {",
    "    for (const pattern of EXPORT_PATTERNS) {",
    "      const re = new RegExp(pattern.re.source, pattern.re.flags);",
    "      let match;",
    "      while ((match = re.exec(content)) !== null) {",
    "        if (pattern.kind === 'list') {",
    "          for (const part of match[1].split(',')) {",
    "            const bits = part.trim().split(/\\s+as\\s+/i);",
    "            addName(names, bits[bits.length - 1]);",
    "          }",
    "        } else {",
    "          addName(names, match[1]);",
    "        }",
    "      }",
    "    }",
    "  } else if (ext === '.py') {",
    "    const re = new RegExp(PYTHON_EXPORT_RE.source, PYTHON_EXPORT_RE.flags);",
    "    let match;",
    "    while ((match = re.exec(content)) !== null) addName(names, match[1]);",
    "  } else if (ext === '.go') {",
    "    const re = new RegExp(GO_EXPORT_RE.source, GO_EXPORT_RE.flags);",
    "    let match;",
    "    while ((match = re.exec(content)) !== null) addName(names, match[1]);",
    "  } else if (ext === '.rs') {",
    "    const re = new RegExp(RUST_EXPORT_RE.source, RUST_EXPORT_RE.flags);",
    "    let match;",
    "    while ((match = re.exec(content)) !== null) addName(names, match[1]);",
    "  }",
    "  return Array.from(names).slice(0, 20);",
    "}",
    "",
    "function collectImports(content, ext) {",
    "  const specs = [];",
    "  if (JS_EXTS.has(ext)) {",
    "    for (const match of content.matchAll(STATIC_IMPORT_RE)) specs.push(match[1]);",
    "    for (const match of content.matchAll(REQUIRE_RE)) specs.push(match[1]);",
    "    for (const match of content.matchAll(DYNAMIC_IMPORT_RE)) specs.push(match[1]);",
    "  } else if (ext === '.py') {",
    "    for (const match of content.matchAll(PYTHON_IMPORT_RE)) {",
    "      const spec = match[1] || match[2];",
    "      if (spec && spec.startsWith('.')) specs.push(spec);",
    "    }",
    "  }",
    "  const unique = [];",
    "  const seen = new Set();",
    "  for (const spec of specs) {",
    "    if (!spec || seen.has(spec)) continue;",
    "    seen.add(spec);",
    "    unique.push(spec);",
    "    if (unique.length >= MAX_IMPORTS_PER_FILE) break;",
    "  }",
    "  return unique;",
    "}",
    "",
    "function languageFor(rel) {",
    "  const ext = path.extname(rel).slice(1).toLowerCase();",
    "  if (EXT_LANG[ext]) return EXT_LANG[ext];",
    "  const base = path.basename(rel).toLowerCase();",
    "  if (base === 'dockerfile') return 'Dockerfile';",
    "  if (base === 'makefile') return 'Makefile';",
    "  return undefined;",
    "}",
    "",
    "function readHead(root) {",
    "  try {",
    "    const out = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], {",
    "      encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],",
    "    }).trim();",
    "    return out || undefined;",
    "  } catch (err) {",
    "    return undefined;",
    "  }",
    "}",
    "",
    "function readChurn(root, sinceHead, churnPath) {",
    "  const churn = {};",
    "  let range = ['--since=90.days'];",
    "  // A rebuild after a commit only has to diff the commits that were added",
    "  // since the last build: the rest of the churn is already on disk.",
    "  if (sinceHead && churnPath) {",
    "    let stored = null;",
    "    try { stored = JSON.parse(fs.readFileSync(churnPath, 'utf8')); } catch (err) { stored = null; }",
    "    if (stored && stored.churn && typeof stored.churn === 'object') {",
    "      for (const key of Object.keys(stored.churn)) churn[key] = stored.churn[key];",
    "      range = [sinceHead + '..HEAD'];",
    "    }",
    "  }",
    "  let out;",
    "  try {",
    "    out = execFileSync('git', ['-C', root, 'log', '--relative', '--no-ext-diff', '--no-textconv', '--no-renames', '--numstat', '--pretty=format:--'].concat(range), {",
    "      encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'],",
    "    });",
    "  } catch (err) {",
    "    // An unusable range (the old commit is gone): fall back to the window.",
    "    if (range.length === 1) return churn;",
    "    range = ['--since=90.days'];",
    "    churn = {};",
    "    try {",
    "      out = execFileSync('git', ['-C', root, 'log', '--relative', '--no-ext-diff', '--no-textconv', '--no-renames', '--numstat', '--pretty=format:--'].concat(range), {",
    "        encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'],",
    "      });",
    "    } catch (err2) {",
    "      return churn;",
    "    }",
    "  }",
    "  for (const line of out.split('\\n')) {",
    "    if (!line || line.startsWith('--')) continue;",
    "    const parts = line.split('\\t');",
    "    if (parts.length < 3) continue;",
    "    const added = parts[0] === '-' ? 0 : (parseInt(parts[0], 10) || 0);",
    "    const removed = parts[1] === '-' ? 0 : (parseInt(parts[1], 10) || 0);",
    "    const file = parts.slice(2).join('\\t').trim();",
    "    if (!file) continue;",
    "    churn[file] = (churn[file] || 0) + added + removed;",
    "  }",
    "  return churn;",
    "}",
    "",
    "function readPackageJson(root) {",
    "  try {",
    "    const raw = fs.readFileSync(path.join(root, 'package.json'), 'utf8');",
    "    const pkg = JSON.parse(raw);",
    "    const out = {};",
    "    if (typeof pkg.name === 'string') out.name = pkg.name;",
    "    if (pkg.scripts && typeof pkg.scripts === 'object') out.scripts = pkg.scripts;",
    "    if (pkg.dependencies && typeof pkg.dependencies === 'object') out.dependencies = pkg.dependencies;",
    "    if (pkg.devDependencies && typeof pkg.devDependencies === 'object') out.devDependencies = pkg.devDependencies;",
    "    if (typeof pkg.packageManager === 'string') out.packageManager = pkg.packageManager;",
    "    return out;",
    "  } catch (err) {",
    "    return undefined;",
    "  }",
    "}",
    "",
    "function summarizePackage(rel, raw) {",
    "  const out = { path: rel };",
    "  try {",
    "    const pkg = JSON.parse(raw);",
    "    if (typeof pkg.name === 'string') out.name = pkg.name;",
    "    if (pkg.scripts && typeof pkg.scripts === 'object') out.scripts = pkg.scripts;",
    "    if (pkg.dependencies && typeof pkg.dependencies === 'object') out.dependencies = pkg.dependencies;",
    "    if (pkg.devDependencies && typeof pkg.devDependencies === 'object') out.devDependencies = pkg.devDependencies;",
    "    if (typeof pkg.packageManager === 'string') out.packageManager = pkg.packageManager;",
    "  } catch (err) {",
    "    return undefined;",
    "  }",
    "  return out;",
    "}",
    "",
    "function listRepos(workspace) {",
    "  const repos = [];",
    "  let entries;",
    "  try {",
    "    entries = fs.readdirSync(workspace, { withFileTypes: true });",
    "  } catch (err) {",
    "    return repos;",
    "  }",
    "  for (const entry of entries) {",
    "    if (!entry.isDirectory()) continue;",
    "    if (entry.name.startsWith('.')) continue;",
    "    const repoRoot = path.join(workspace, entry.name);",
    "    let isRepo = false;",
    "    try { isRepo = fs.existsSync(path.join(repoRoot, '.git')); } catch (err) { isRepo = false; }",
    "    if (!isRepo) continue;",
    "    repos.push({ repo: entry.name, repoRoot: repoRoot, name: entry.name });",
    "  }",
    "  let workspaceIsRepo = false;",
    "  try { workspaceIsRepo = fs.existsSync(path.join(workspace, '.git')); } catch (err) { workspaceIsRepo = false; }",
    "  if (workspaceIsRepo) repos.unshift({ repo: '', repoRoot: workspace, name: path.basename(workspace) });",
    "  return repos;",
    "}",
    "",
    "function scan(root, sinceHead, churnPath) {",
    "  const absRoot = path.resolve(root);",
    "  const walked = walk(absRoot);",
    "  const files = [];",
    "  const packageFiles = [];",
    "  const lockFiles = walked.lockFiles;",
    "  for (const rel of walked.files) {",
    "    const abs = path.join(absRoot, rel);",
    "    let stat;",
    "    try { stat = fs.statSync(abs); } catch (err) { continue; }",
    "    const ext = path.extname(rel).toLowerCase();",
    "    const record = { path: rel, bytes: stat.size, mtimeMs: Math.round(stat.mtimeMs) };",
    "    const language = languageFor(rel);",
    "    if (language) record.language = language;",
    "    const baseName = path.basename(rel);",
    "    if (LOCK_FILES.has(baseName)) lockFiles.push(baseName);",
    "    if (path.basename(rel) === 'package.json' && packageFiles.length < 25) {",
    "      let raw;",
    "      try { raw = fs.readFileSync(abs, 'utf8'); } catch (err) { raw = null; }",
    "      if (raw != null) {",
    "        const summary = summarizePackage(rel, raw);",
    "        if (summary) packageFiles.push(summary);",
    "      }",
    "    }",
    "    if (SOURCE_EXTS.has(ext) && stat.size <= MAX_PARSED_FILE_BYTES) {",
    "      let content;",
    "      try { content = fs.readFileSync(abs, 'utf8'); } catch (err) { content = null; }",
    "      if (content != null && !looksBinary(content)) {",
    "        record.lines = countLines(content);",
    "        record.complexity = countComplexity(content);",
    "        record.head = content.slice(0, 300);",
    "        const exports = extractExports(content, ext);",
    "        if (exports.length) record.exports = exports;",
    "        const imports = collectImports(content, ext);",
    "        if (imports.length) record.imports = imports;",
    "      }",
    "    }",
    "    files.push(record);",
    "  }",
    "  const head = readHead(absRoot);",
    "  const churn = readChurn(absRoot, sinceHead, churnPath);",
    "  const coverage = readCoverage(absRoot);",
    "  return {",
    "    repoRoot: absRoot,",
    "    repoName: path.basename(absRoot) || absRoot,",
    "    repoHash: repoHash(absRoot),",
    "    generatedAt: new Date().toISOString(),",
    "    gitHead: head,",
    "    files,",
    "    churn,",
    "    ...(Object.keys(coverage).length ? { coverage } : {}),",
    "    packageJson: readPackageJson(absRoot),",
    "    packageFiles,",
    "    lockFiles,",
    "    truncated: walked.truncated,",
    "  };",
    "}",
    "",
    "const args = process.argv.slice(2);",
    "if (args[0] === '--list-repos') {",
    "  const workspace = path.resolve(args[1] || '/workspace');",
    "  process.stdout.write(JSON.stringify({ ok: true, repos: listRepos(workspace) }));",
    "  process.exit(0);",
    "}",
    "",
    "const target = path.resolve(args[0] || '/workspace');",
    "const sinceHead = args[1] && args[1] !== '-' ? args[1] : undefined;",
    "let stat;",
    "try { stat = fs.statSync(target); } catch (err) { stat = null; }",
    "if (!stat || !stat.isDirectory()) {",
    "  process.stdout.write(JSON.stringify({ ok: false, error: 'not_a_directory', repoRoot: target }));",
    "  process.exit(2);",
    "}",
    "",
    "// The scan is written next to the finished map so the server can read it",
    "// back without pushing megabytes through the exec output quota.",
    "const home = process.env.HOME || '/home/node';",
    "const dir = path.join(home, '.swarm', 'codebase', repoHash(target));",
    "const scanPath = path.join(dir, 'scan.json');",
    "const churnPath = path.join(dir, 'churn.json');",
    "const result = scan(target, sinceHead, churnPath);",
    "try {",
    "  fs.mkdirSync(dir, { recursive: true });",
    "  fs.writeFileSync(scanPath, JSON.stringify(result));",
    "  fs.writeFileSync(churnPath, JSON.stringify({ head: result.gitHead, churn: result.churn }));",
    "} catch (err) {",
    "  process.stdout.write(JSON.stringify({ ok: false, error: 'write_failed', repoRoot: target }));",
    "  process.exit(3);",
    "}",
    "process.stdout.write(JSON.stringify({ ok: true, scanPath: scanPath, files: result.files.length }));",
    "",
  ];
  return lines.join("\n");
}
