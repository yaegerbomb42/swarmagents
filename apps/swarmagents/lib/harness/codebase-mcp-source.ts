/**
 * The codebase MCP server.
 *
 * The server is written into the user's VM next to the role-switch server and
 * exposed to the agent as the `codebase` MCP server. It exposes two tools:
 *
 *   - codebase_map_get()      — the context pack: languages, entry points,
 *     commands, module layout and the files everything else depends on.
 *   - codebase_hotspots(n)    — the hottest files (churn x size x fan-in x
 *     the files the agent touched before).
 *
 * It reads the map the app published in the VM
 * (`~/.swarm/codebase/<repoHash>/map.json`), so the agent and the UI always
 * talk about the same map.
 */

/** Name of the stdio MCP server exposing the codebase tools. */
export const CODEBASE_MCP_SERVER_NAME = "codebase";

/** Path (inside the VM) the server is written to. */
export const CODEBASE_MCP_SERVER_PATH = "/workspace/.swarm/codebase-server.mjs";

/** The tool the agent calls to read the map. */
export const CODEBASE_MAP_TOOL = "codebase_map_get";

/** The tool the agent calls to list the hottest files. */
export const CODEBASE_HOTSPOTS_TOOL = "codebase_hotspots";

/** The server program, written verbatim into the VM. */
export function codebaseMcpServerSource(): string {
  return [
    "#!/usr/bin/env node",
    "// SwarmAgents codebase MCP stdio server (auto-generated).",
    "// Speaks newline-delimited JSON-RPC 2.0 over stdin/stdout.",
    "import fs from 'node:fs';",
    "import path from 'node:path';",
    "import crypto from 'node:crypto';",
    "",
    "function repoHash(root) {",
    "  return crypto.createHash('sha1').update(path.resolve(root)).digest('hex').slice(0, 16);",
    "}",
    "",
    "function readJson(file) {",
    "  try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch (err) { return null; }",
    "}",
    "",
    "function mapDir(hash) {",
    "  const home = process.env.HOME || '/root';",
    "  return path.join(home, '.swarm', 'codebase', hash);",
    "}",
    "",
    "function loadMap(repoRoot) {",
    "  const hash = repoHash(repoRoot);",
    "  const direct = readJson(path.join(mapDir(hash), 'map.json'));",
    "  if (direct) return direct;",
    "  // The workspace may hold several repositories: fall back to the newest",
    "  // map that mentions this repository root.",
    "  try {",
    "    const base = path.join(process.env.HOME || '/root', '.swarm', 'codebase');",
    "    const dirs = fs.readdirSync(base, { withFileTypes: true });",
    "    const maps = [];",
    "    for (const dir of dirs) {",
    "      if (!dir.isDirectory()) continue;",
    "      const map = readJson(path.join(base, dir.name, 'map.json'));",
    "      if (map) maps.push(map);",
    "    }",
    "    const exact = maps.find((map) => map.repoRoot === repoRoot);",
    "    if (exact) return exact;",
    "    maps.sort((a, b) => String(b.generatedAt || '').localeCompare(String(a.generatedAt || '')));",
    "    return maps[0] || null;",
    "  } catch (err) {",
    "    return null;",
    "  }",
    "}",
    "",
    "// The repository the account picked in the Codebase tab, if any.",
    "function selectedRepo() {",
    "  const selection = readJson(path.join(process.env.HOME || '/root', '.swarm', 'codebase', 'selection.json'));",
    "  return selection && typeof selection.repoRoot === 'string' && selection.repoRoot",
    "    ? selection.repoRoot",
    "    : null;",
    "}",
    "",
    "const tools = [",
    "  {",
    "    name: 'codebase_map_get',",
    "    description: 'Get the codebase map for the active repository: languages, entry points, build and test commands, top-level modules, key files by import fan-in and the conventions used (test framework, lint, formatting). Use it to orient yourself before editing.',",
    "    inputSchema: {",
    "      type: 'object',",
    "      properties: {",
    "        repoRoot: { type: 'string', description: 'Optional repository root inside the workspace.' }",
    "      }",
    "    }",
    "  },",
    "  {",
    "    name: 'codebase_hotspots',",
    "    description: 'Get the hottest files of the active repository, ranked by churn (last 90 days) x size x import fan-in x the files this agent touched before. Use it to decide where a change is risky.',",
    "    inputSchema: {",
    "      type: 'object',",
    "      properties: {",
    "        n: { type: 'number', description: 'How many hotspots to return (default 20, max 200).' },",
    "        repoRoot: { type: 'string', description: 'Optional repository root inside the workspace.' }",
    "      }",
    "    }",
    "  }",
    "];",
    "",
    "function reply(id, result) {",
    "  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: id, result: result }) + '\\n');",
    "}",
    "",
    "function replyError(id, code, message) {",
    "  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: id, error: { code: code, message: message } }) + '\\n');",
    "}",
    "",
    "function toolResult(payload, isError) {",
    "  return {",
    "    content: [{ type: 'text', text: JSON.stringify(payload) }],",
    "    isError: isError === true",
    "  };",
    "}",
    "",
    "function callTool(name, args) {",
    "  // Explicit argument, then the repository the account picked, then the",
    "  // workspace root the MCP config defaults to.",
    "  const repoRoot = (typeof args.repoRoot === 'string' && args.repoRoot.trim())",
    "    ? args.repoRoot.trim()",
    "    : (selectedRepo() || process.env.SWARM_CODEBASE_REPO_ROOT || '/workspace');",
    "  const map = loadMap(repoRoot);",
    "  if (!map) {",
    "    return toolResult({",
    "      ok: false,",
    "      error: 'codebase map not found',",
    "      repoRoot: repoRoot,",
    "      hint: 'The map is built when a repository is picked in the Codebase tab.'",
    "    }, true);",
    "  }",
    "  if (name === 'codebase_map_get') {",
    "    const pack = map.contextPack || {};",
    "    return toolResult({",
    "      ok: true,",
    "      repoRoot: map.repoRoot,",
    "      repoName: map.repoName,",
    "      repoHash: map.repoHash,",
    "      generatedAt: map.generatedAt,",
    "      gitHead: map.gitHead,",
    "      buildMs: map.buildMs,",
    "      tokenEstimate: pack.tokenEstimate,",
    "      languages: map.languages,",
    "      entryPoints: map.entryPoints,",
    "      buildCommands: map.buildCommands,",
    "      testCommands: map.testCommands,",
    "      conventions: map.conventions,",
    "      topLevelModules: map.topLevelModules,",
    "      keyFiles: (pack.keyFiles || []).slice(0, 40),",
    "      contextPack: pack.text",
    "    }, false);",
    "  }",
    "  if (name === 'codebase_hotspots') {",
    "    const raw = Number(args.n);",
    "    const n = Math.max(1, Math.min(200, Number.isFinite(raw) && raw > 0 ? Math.floor(raw) : 20));",
    "    const hotspots = Array.isArray(map.heatmap) ? map.heatmap.slice(0, n) : [];",
    "    return toolResult({",
    "      ok: true,",
    "      repoRoot: map.repoRoot,",
    "      repoHash: map.repoHash,",
    "      n: n,",
    "      hotspots: hotspots",
    "    }, false);",
    "  }",
    "  return toolResult({ ok: false, error: 'unknown tool: ' + name }, true);",
    "}",
    "",
    "function handleMessage(msg) {",
    "  if (!msg || typeof msg !== 'object') return;",
    "  const hasId = msg.id !== undefined && msg.id !== null;",
    "  const method = typeof msg.method === 'string' ? msg.method : '';",
    "  if (method === 'initialize') {",
    "    if (hasId) reply(msg.id, {",
    "      protocolVersion: (msg.params && msg.params.protocolVersion) || '2024-11-05',",
    "      capabilities: { tools: {} },",
    "      serverInfo: { name: 'swarm-codebase', version: '1.0.0' }",
    "    });",
    "    return;",
    "  }",
    "  if (method === 'ping') {",
    "    if (hasId) reply(msg.id, {});",
    "    return;",
    "  }",
    "  if (method === 'tools/list') {",
    "    if (hasId) reply(msg.id, { tools: tools });",
    "    return;",
    "  }",
    "  if (method === 'tools/call') {",
    "    const params = msg.params && typeof msg.params === 'object' ? msg.params : {};",
    "    const name = typeof params.name === 'string' ? params.name : '';",
    "    const args = params.arguments && typeof params.arguments === 'object' ? params.arguments : {};",
    "    if (hasId) reply(msg.id, callTool(name, args));",
    "    return;",
    "  }",
    "  if (method === 'notifications/initialized' || method === 'notifications/cancelled') return;",
    "  if (hasId) replyError(msg.id, -32601, 'Method not found: ' + method);",
    "}",
    "",
    "process.stdin.setEncoding('utf8');",
    "let buffer = '';",
    "process.stdin.on('data', (chunk) => {",
    "  buffer += chunk;",
    "  let newline;",
    "  while ((newline = buffer.indexOf('\\n')) !== -1) {",
    "    const line = buffer.slice(0, newline).trim();",
    "    buffer = buffer.slice(newline + 1);",
    "    if (!line) continue;",
    "    let msg;",
    "    try { msg = JSON.parse(line); } catch (err) { continue; }",
    "    handleMessage(msg);",
    "  }",
    "});",
    "",
  ].join("\n");
}
