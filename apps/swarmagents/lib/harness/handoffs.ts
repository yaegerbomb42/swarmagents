/**
 * Pending ask_human_desktop handoffs.
 *
 * Handoffs are created when the agent calls ask_human_desktop and resolved when
 * the user clicks "Hand Back to Agent" through POST /api/runtime/handoffs.
 * They are persisted to a JSON file (under SWARM_HOME) so a page reload — or
 * even a server restart — still shows an unresolved "Take the Wheel" card
 * instead of losing the paused run.
 *
 * The in-memory map of waiters is the authority for resuming a run; disk is
 * only a mirror used to re-render pending cards. Timer/waiter/persistence
 * mechanics live in PendingInteractionStore (see ./pending-store.ts).
 */

import path from "node:path";
import { randomUUID } from "node:crypto";
import { getStoragePaths } from "../board/store";
import { DESKTOP_HANDOFF_TTL_MS } from "./desktop-handoff-mcp";
import {
  PendingInteractionStore,
  type BasePendingInteraction,
} from "./pending-store";

export type HandoffStatus = "pending" | "answered" | "expired" | "cancelled";

export interface PendingHandoff extends BasePendingInteraction {
  reason: string;
  description: string;
  status: HandoffStatus;
}

export type HandoffOutcome =
  | { status: "answered" }
  | { status: "expired" }
  | { status: "cancelled" };

export interface CreateHandoffInput {
  /** Id generated by the VM-side desktop-handoff server; a random one when absent. */
  id?: string;
  runId: string;
  userId: string;
  reason: string;
  description?: string;
  ttlMs?: number;
}

export interface HandoffStoreOptions {
  ttlMs?: number;
  now?: () => number;
  /** Override persistence path (tests); defaults to <storage>/handoffs.json. */
  filePath?: string;
  /** Disable disk persistence (tests that don't care). */
  persist?: boolean;
}

function defaultTtlMs(): number {
  const fromSec = Number(process.env.SWARM_HANDOFF_TIMEOUT_SEC);
  if (Number.isFinite(fromSec) && fromSec > 0) return fromSec * 1000;
  return DESKTOP_HANDOFF_TTL_MS;
}

function defaultFilePath(): string {
  return path.join(getStoragePaths().STORAGE_DIR, "handoffs.json");
}

function normalizeHandoff(raw: unknown, nowMs: number): PendingHandoff | null {
  if (!raw || typeof raw !== "object") return null;
  const h = raw as Partial<PendingHandoff>;
  if (typeof h.id !== "string" || typeof h.reason !== "string") return null;
  const status: HandoffStatus =
    h.status === "answered" || h.status === "expired" || h.status === "cancelled"
      ? h.status
      : "pending";
  const expiresAt = typeof h.expiresAt === "number" ? h.expiresAt : nowMs;
  return {
    id: h.id,
    runId: typeof h.runId === "string" ? h.runId : "",
    userId: typeof h.userId === "string" ? h.userId : "",
    reason: h.reason,
    description: typeof h.description === "string" ? h.description : "",
    createdAt: typeof h.createdAt === "number" ? h.createdAt : nowMs,
    expiresAt,
    status: status === "pending" && expiresAt <= nowMs ? "expired" : status,
  };
}

export class HandoffStore extends PendingInteractionStore<PendingHandoff, HandoffOutcome> {
  private readonly ttlMs: number | undefined;

  constructor(options: HandoffStoreOptions = {}) {
    super({
      filePath: options.filePath ?? defaultFilePath(),
      persist: options.persist,
      now: options.now,
      auditExpireAction: "handoff.expire",
      normalize: normalizeHandoff,
      expiredOutcome: () => ({ status: "expired" }),
      cancelledOutcome: () => ({ status: "cancelled" }),
      // A late waitFor() on a decided handoff reports the stored outcome.
      decidedOutcome: (item) => ({
        status: item.status === "answered" ? "answered" : item.status === "expired" ? "expired" : "cancelled",
      }),
      // Keep decided handoffs 24h so a late waiter still gets its outcome.
      decidedRetentionMs: 24 * 60 * 60 * 1000,
    });
    this.ttlMs = options.ttlMs;
  }

  /** Create a pending handoff and start its TTL timer. */
  create(input: CreateHandoffInput): PendingHandoff {
    const now = this.now();
    const ttlMs = input.ttlMs ?? this.ttlMs ?? defaultTtlMs();
    return this.createPending(
      {
        id: input.id || `h_${randomUUID()}`,
        runId: input.runId,
        userId: input.userId,
        reason: input.reason,
        description: input.description ?? "",
        createdAt: now,
        expiresAt: now + ttlMs,
        status: "pending",
      },
      ttlMs,
    );
  }

  /** Resolve a pending handoff (user clicked "Hand Back to Agent"). Idempotent. */
  resolve(id: string): PendingHandoff | undefined {
    return this.settle(id, (item) => {
      item.status = "answered";
      return { status: "answered" };
    });
  }
}

const g = globalThis as typeof globalThis & { __swarmHandoffStore?: HandoffStore };
export function getHandoffStore(): HandoffStore {
  return g.__swarmHandoffStore ?? (g.__swarmHandoffStore = new HandoffStore());
}
export function setHandoffStoreForTesting(store: HandoffStore | null): void {
  g.__swarmHandoffStore = store ?? undefined;
}
