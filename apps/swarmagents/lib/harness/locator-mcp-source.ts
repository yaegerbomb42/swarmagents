/**
 * The locator MCP server.
 *
 * The server is written into the user's VM next to the codebase server and
 * exposed to the agent as the `locator` MCP server. It exposes one tool:
 *
 *   - locate_code(query, limit?) — ripgrep-backed search over the live
 *     workspace tree: the agent describes a symbol, error message, or
 *     concept in plain words and gets back the top matching files with
 *     exact line numbers and snippets, ranked by relevance.
 *
 * Ported from `vendor/claude-code-mini/src/autoLocator.ts`
 * (`AutoLocator.locate`): the query cleaning (strip quotes, keep word
 * chars/dot/hyphen, drop short words, keep at most three keywords) and the
 * ripgrep flags (`-n -i -m 5 --max-columns 120`, excluding node_modules,
 * .git, dist, .next) are the vendor's. The vendor version interpolates the
 * query into a shell command string; this port never does — ripgrep is
 * spawned with an argv array and no shell, so the query is always data.
 *
 * The search runs inside the VM (where the workspace files are) and is
 * scoped to the workspace root: the server's cwd is the root and ripgrep
 * only ever searches `.` beneath it. No keys or secrets are involved.
 */

/** Name of the stdio MCP server exposing the locator tool. */
export const LOCATOR_MCP_SERVER_NAME = "locator";

/** Path (inside the VM) the server is written to. */
export const LOCATOR_MCP_SERVER_PATH = "/workspace/.swarm/locator-server.mjs";

/** The tool the agent calls to locate code. */
export const LOCATOR_TOOL = "locate_code";

/** The server program, written verbatim into the VM. */
export function locatorMcpServerSource(): string {
  return [
    "#!/usr/bin/env node",
    "// SwarmAgents locator MCP stdio server (auto-generated).",
    "// Speaks newline-delimited JSON-RPC 2.0 over stdin/stdout.",
    "import path from 'node:path';",
    "import { spawnSync } from 'node:child_process';",
    "",
    "const SEARCH_TIMEOUT_MS = 5000;",
    "const MAX_BUFFER_BYTES = 2 * 1024 * 1024;",
    "const MAX_PARSED_LINES = 200;",
    "const DEFAULT_LIMIT = 3;",
    "const MAX_LIMIT = 10;",
    "",
    "function workspaceRoot() {",
    "  const root = process.env.SWARM_LOCATOR_ROOT;",
    "  return path.resolve(typeof root === 'string' && root.trim() !== '' ? root.trim() : '/workspace');",
    "}",
    "",
    "// Vendor query cleaning (AutoLocator): strip quotes, keep word chars,",
    "// dot and hyphen, drop words of length <= 2, keep at most three keywords.",
    "function cleanKeywords(query) {",
    "  return String(query || '')",
    "    .replace(/['\"]/g, '')",
    "    .replace(/[^\\w\\s.-]/g, ' ')",
    "    .trim()",
    "    .split(/\\s+/)",
    "    .filter((word) => word.length > 2)",
    "    .slice(0, 3);",
    "}",
    "",
    "// Deterministic relevance score: a whole-word keyword hit in the snippet",
    "// and a keyword in the file name count most; a substring hit counts less;",
    "// a definition line (function/class/const/...) outranks a mere mention.",
    "const DEFINITION_HINT = /\\b(function|class|const|let|var|interface|type|enum)\\b/;",
    "",
    "function scoreMatch(filePath, snippet, keywords) {",
    "  const lowerSnippet = snippet.toLowerCase();",
    "  const words = lowerSnippet.split(/[^\\w.-]+/);",
    "  const base = path.basename(filePath).toLowerCase();",
    "  let score = 1;",
    "  if (DEFINITION_HINT.test(lowerSnippet)) score += 2;",
    "  for (const keyword of keywords) {",
    "    const kw = keyword.toLowerCase();",
    "    if (words.includes(kw)) score += 2;",
    "    else if (lowerSnippet.includes(kw)) score += 1;",
    "    if (base.includes(kw)) score += 2;",
    "  }",
    "  return score;",
    "}",
    "",
    "function locate(query, limit) {",
    "  const keywords = cleanKeywords(query);",
    "  if (keywords.length === 0) return { keywords: keywords, targets: [] };",
    "  const root = workspaceRoot();",
    "  const pattern = keywords.join('|');",
    "  // argv array only, no shell: the pattern is data, never shell text.",
    "  // '-e' keeps a pattern that starts with '-' from being read as a flag;",
    "  // '--' + '.' scopes the search to the workspace root (cwd).",
    "  const result = spawnSync('rg', [",
    "    '-n', '-i', '-m', '5', '--max-columns', '120', '--no-heading',",
    "    '-g', '!node_modules', '-g', '!.git', '-g', '!dist', '-g', '!.next',",
    "    '-e', pattern, '--', '.'",
    "  ], {",
    "    cwd: root,",
    "    encoding: 'utf8',",
    "    timeout: SEARCH_TIMEOUT_MS,",
    "    maxBuffer: MAX_BUFFER_BYTES,",
    "    shell: false",
    "  });",
    "  if (result.error) {",
    "    if (result.error.code === 'ENOENT') {",
    "      return { error: 'ripgrep (rg) is not available in this VM image' };",
    "    }",
    "    if (result.error.code === 'ETIMEDOUT') {",
    "      return { error: 'locate_code timed out after ' + SEARCH_TIMEOUT_MS + 'ms' };",
    "    }",
    "    return { error: 'locate_code failed: ' + result.error.message };",
    "  }",
    "  // rg exit 1 = no matches (not an error); exit 2 = rg itself failed.",
    "  if (result.status === 1) return { keywords: keywords, targets: [] };",
    "  if (result.status !== 0) {",
    "    const detail = String(result.stderr || '').trim().slice(0, 200);",
    "    return { error: 'ripgrep exited with status ' + result.status + (detail ? ': ' + detail : '') };",
    "  }",
    "  const lines = String(result.stdout || '').split('\\n').filter(Boolean).slice(0, MAX_PARSED_LINES);",
    "  const targets = [];",
    "  for (const line of lines) {",
    "    const parts = line.split(':');",
    "    if (parts.length < 3) continue;",
    "    const filePath = parts[0].replace(/^\\.\\//, '');",
    "    const lineNum = parseInt(parts[1], 10);",
    "    const snippet = parts.slice(2).join(':').trim().slice(0, 120);",
    "    targets.push({",
    "      filePath: filePath,",
    "      line: Number.isNaN(lineNum) ? 1 : lineNum,",
    "      snippet: snippet,",
    "      score: scoreMatch(filePath, snippet, keywords)",
    "    });",
    "  }",
    "  targets.sort((a, b) => (b.score - a.score) || a.filePath.localeCompare(b.filePath) || (a.line - b.line));",
    "  return { keywords: keywords, targets: targets.slice(0, limit) };",
    "}",
    "",
    "const tools = [",
    "  {",
    "    name: 'locate_code',",
    "    description: 'Search the workspace for a symbol, error message, or concept and get back the top matching files with exact line numbers and snippets, ranked by relevance. Use it to find where something lives before reading whole files.',",
    "    inputSchema: {",
    "      type: 'object',",
    "      properties: {",
    "        query: { type: 'string', description: 'Symbol, error text, or concept to locate (plain words).' },",
    "        limit: { type: 'number', description: 'How many targets to return (default 3, max 10).' }",
    "      },",
    "      required: ['query']",
    "    }",
    "  }",
    "];",
    "",
    "function reply(id, result) {",
    "  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: id, result: result }) + '\\n');",
    "}",
    "",
    "function replyError(id, code, message) {",
    "  process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id: id, error: { code: code, message: message } }) + '\\n');",
    "}",
    "",
    "function toolResult(payload, isError) {",
    "  return {",
    "    content: [{ type: 'text', text: JSON.stringify(payload) }],",
    "    isError: isError === true",
    "  };",
    "}",
    "",
    "function callTool(name, args) {",
    "  if (name !== 'locate_code') {",
    "    return toolResult({ ok: false, error: 'unknown tool: ' + name }, true);",
    "  }",
    "  const query = typeof args.query === 'string' ? args.query : '';",
    "  const rawLimit = Number(args.limit);",
    "  const limit = Math.max(1, Math.min(MAX_LIMIT, Number.isFinite(rawLimit) && rawLimit > 0 ? Math.floor(rawLimit) : DEFAULT_LIMIT));",
    "  const found = locate(query, limit);",
    "  if (found.error) {",
    "    return toolResult({ ok: false, error: found.error }, true);",
    "  }",
    "  const text = found.targets.map((t) => t.filePath + ':' + t.line + ' ' + t.snippet).join('\\n');",
    "  return toolResult({",
    "    ok: true,",
    "    query: query,",
    "    keywords: found.keywords,",
    "    targets: found.targets,",
    "    text: text",
    "  }, false);",
    "}",
    "",
    "function handleMessage(msg) {",
    "  if (!msg || typeof msg !== 'object') return;",
    "  const hasId = msg.id !== undefined && msg.id !== null;",
    "  const method = typeof msg.method === 'string' ? msg.method : '';",
    "  if (method === 'initialize') {",
    "    if (hasId) reply(msg.id, {",
    "      protocolVersion: (msg.params && msg.params.protocolVersion) || '2024-11-05',",
    "      capabilities: { tools: {} },",
    "      serverInfo: { name: 'swarm-locator', version: '1.0.0' }",
    "    });",
    "    return;",
    "  }",
    "  if (method === 'ping') {",
    "    if (hasId) reply(msg.id, {});",
    "    return;",
    "  }",
    "  if (method === 'tools/list') {",
    "    if (hasId) reply(msg.id, { tools: tools });",
    "    return;",
    "  }",
    "  if (method === 'tools/call') {",
    "    const params = msg.params && typeof msg.params === 'object' ? msg.params : {};",
    "    const name = typeof params.name === 'string' ? params.name : '';",
    "    const args = params.arguments && typeof params.arguments === 'object' ? params.arguments : {};",
    "    if (hasId) reply(msg.id, callTool(name, args));",
    "    return;",
    "  }",
    "  if (method === 'notifications/initialized' || method === 'notifications/cancelled') return;",
    "  if (hasId) replyError(msg.id, -32601, 'Method not found: ' + method);",
    "}",
    "",
    "process.stdin.setEncoding('utf8');",
    "let buffer = '';",
    "process.stdin.on('data', (chunk) => {",
    "  buffer += chunk;",
    "  let newline;",
    "  while ((newline = buffer.indexOf('\\n')) !== -1) {",
    "    const line = buffer.slice(0, newline).trim();",
    "    buffer = buffer.slice(newline + 1);",
    "    if (!line) continue;",
    "    let msg;",
    "    try { msg = JSON.parse(line); } catch (err) { continue; }",
    "    handleMessage(msg);",
    "  }",
    "});",
    "",
    "process.stdin.on('end', () => {});",
    "",
  ].join("\n");
}
