/**
 * More provider catalog entries, ported from the Omnexx reference catalog
 * (vendor/omnexx/src/providers/catalog*.ts, checked against each provider's
 * docs in 2026-10). Every entry speaks the OpenAI Chat Completions API, so
 * Claude Code reaches it through the existing Anthropic ↔ OpenAI translation
 * proxy (app/api/runtime/llm) with no new wire code.
 *
 * Pure data, safe for client components (same rules as catalog.ts):
 *  - links are the provider's own pages only; a link we could not verify is
 *    left out rather than guessed;
 *  - an API root that depends on the account (Azure resource, Cloudflare
 *    account id, Vertex project, …) is NOT given a placeholder baseUrl —
 *    authHint shows the URL shape and the user pastes their own;
 *  - models are left out: these hosts serve hundreds of ids, and model
 *    discovery (GET /models) fills the list once a key is added.
 *
 * Keys are never read from here. envVar only names the single-user
 * SWARM_KEYS_* slot; in server mode every key comes from the signed-in
 * user's own saved provider config.
 *
 * Providers the main catalog already covers under another id are skipped
 * (Omnexx nvidia = nvidia-nim, azure = azure-openai, bedrock = aws-bedrock).
 */

