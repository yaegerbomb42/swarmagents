'use client';

/**
 * ExportMissionReportButton — compact export control for mission sessions.
 * Provides JSON download, Markdown report generation, and share-link copy
 * via a Framer Motion animated popover.
 */

import { useCallback, useEffect, useRef, useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { Download, Check, FileJson, FileText, Link2 } from 'lucide-react';

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface ExportMissionReportButtonProps {
  sessionId?: string;
  projectId?: string;
  missionLabel?: string;
  className?: string;
}

type ExportStatus = 'idle' | 'success';

// ---------------------------------------------------------------------------
// Markdown generator
// ---------------------------------------------------------------------------

function generateMarkdownReport(params: {
  missionLabel: string;
  sessionId: string;
  stats?: { tasksCompleted?: number; totalTokens?: number; durationSec?: number };
}): string {
  const date = new Date().toISOString().slice(0, 10);
  const dur = params.stats?.durationSec
    ? `${Math.floor(params.stats.durationSec / 60)}m ${params.stats.durationSec % 60}s`
    : 'N/A';
  return [
    `# Mission Report — ${params.missionLabel}`,
    ``,
    `**Session ID:** \`${params.sessionId}\`  `,
    `**Generated:** ${date}  `,
    ``,
    `## Summary`,
    ``,
    `| Metric | Value |`,
    `|--------|-------|`,
    `| Tasks Completed | ${params.stats?.tasksCompleted ?? '—'} |`,
    `| Total Tokens | ${params.stats?.totalTokens ?? '—'} |`,
    `| Duration | ${dur} |`,
    ``,
    `## Task Tree`,
    ``,
    `*Full task tree available in the JSON export.*`,
    ``,
    `---`,
    `*Generated by SwarmAgents*`,
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Download helpers
// ---------------------------------------------------------------------------

function triggerDownload(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

function dateStamp(): string {
  return new Date().toISOString().slice(0, 10);
}

// ---------------------------------------------------------------------------
// Sub-component: individual option row
// ---------------------------------------------------------------------------

interface OptionRowProps {
  icon: React.ReactNode;
  label: string;
  description: string;
  onClick: () => void;
  disabled?: boolean;
}

function OptionRow({ icon, label, description, onClick, disabled = false }: OptionRowProps) {
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={disabled}
      className={[
        'flex w-full items-center gap-3 rounded-lg px-3 py-2.5 text-left transition-colors',
        'hover:bg-white/[0.04] active:bg-white/[0.07]',
        'disabled:pointer-events-none disabled:opacity-40',
        'focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-cyan-400/60',
      ].join(' ')}
    >
      <span className="shrink-0 text-zinc-400">{icon}</span>
      <div className="min-w-0 flex-1">
        <p className="text-[11px] font-medium text-zinc-100 leading-none">{label}</p>
        <p className="mt-0.5 text-[10px] text-zinc-500 leading-tight">{description}</p>
      </div>
    </button>
  );
}

// ---------------------------------------------------------------------------
// Main component
// ---------------------------------------------------------------------------

export default function ExportMissionReportButton({
  sessionId,
  projectId: _projectId,
  missionLabel = 'Untitled Mission',
  className = '',
}: ExportMissionReportButtonProps) {
  const [open, setOpen] = useState(false);
  const [buttonStatus, setButtonStatus] = useState<ExportStatus>('idle');
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  const containerRef = useRef<HTMLDivElement>(null);
  const successTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null);
  const toastTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  // ---- Close on outside click ----
  useEffect(() => {
    if (!open) return;
    function handleMousedown(e: MouseEvent) {
      if (containerRef.current && !containerRef.current.contains(e.target as Node)) {
        setOpen(false);
      }
    }
    document.addEventListener('mousedown', handleMousedown);
    return () => document.removeEventListener('mousedown', handleMousedown);
  }, [open]);

  // ---- Close on Escape ----
  useEffect(() => {
    if (!open) return;
    function handleKeydown(e: KeyboardEvent) {
      if (e.key === 'Escape') setOpen(false);
    }
    document.addEventListener('keydown', handleKeydown);
    return () => document.removeEventListener('keydown', handleKeydown);
  }, [open]);

  // ---- Cleanup timers on unmount ----
  useEffect(() => {
    return () => {
      if (successTimerRef.current) clearTimeout(successTimerRef.current);
      if (toastTimerRef.current) clearTimeout(toastTimerRef.current);
    };
  }, []);

  // ---- Flash success state on trigger button ----
  const flashSuccess = useCallback(() => {
    setButtonStatus('success');
    if (successTimerRef.current) clearTimeout(successTimerRef.current);
    successTimerRef.current = setTimeout(() => setButtonStatus('idle'), 1500);
  }, []);

  // ---- Show toast ----
  const showToast = useCallback((msg: string) => {
    setToastMessage(msg);
    if (toastTimerRef.current) clearTimeout(toastTimerRef.current);
    toastTimerRef.current = setTimeout(() => setToastMessage(null), 2500);
  }, []);

  // ---- Export handlers ----
  const handleExportJson = useCallback(async () => {
    setOpen(false);
    if (!sessionId) {
      showToast('No session ID — cannot fetch data');
      return;
    }
    try {
      const res = await fetch(`/api/tasks/${sessionId}`);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data: unknown = await res.json();
      triggerDownload(
        JSON.stringify(data, null, 2),
        `mission-${sessionId}-${dateStamp()}.json`,
        'application/json',
      );
      flashSuccess();
    } catch (err) {
      showToast(err instanceof Error ? err.message : 'JSON export failed');
    }
  }, [sessionId, flashSuccess, showToast]);

  const handleExportMarkdown = useCallback(() => {
    setOpen(false);
    const id = sessionId ?? 'unknown';
    const content = generateMarkdownReport({ missionLabel, sessionId: id });
    triggerDownload(
      content,
      `mission-${id}-${dateStamp()}.md`,
      'text/markdown',
    );
    flashSuccess();
  }, [sessionId, missionLabel, flashSuccess]);

  const handleShareLink = useCallback(async () => {
    setOpen(false);
    const id = sessionId ?? '';
    const url = `${window.location.origin}/decomp?session=${id}`;
    try {
      await navigator.clipboard.writeText(url);
      showToast('Share link copied!');
      flashSuccess();
    } catch {
      showToast('Clipboard write failed');
    }
  }, [sessionId, flashSuccess, showToast]);

  const hasSession = Boolean(sessionId);

  return (
    <div ref={containerRef} className={`relative inline-flex ${className}`}>
      {/* ---- Trigger button ---- */}
      <button
        type="button"
        aria-label="Export mission report"
        aria-expanded={open}
        aria-haspopup="menu"
        onClick={() => setOpen((v) => !v)}
        className={[
          'inline-flex items-center gap-1.5 rounded-lg border px-2.5 py-1.5',
          'text-[11px] font-medium transition-colors',
          'border-white/[0.08] bg-white/[0.04] text-zinc-300',
          'hover:border-cyan-400/30 hover:bg-cyan-400/[0.06] hover:text-cyan-300',
          'focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-cyan-400/60',
          'active:scale-[0.97]',
        ].join(' ')}
      >
        <AnimatePresence mode="wait" initial={false}>
          {buttonStatus === 'success' ? (
            <motion.span
              key="check"
              initial={{ opacity: 0, scale: 0.7 }}
              animate={{ opacity: 1, scale: 1 }}
              exit={{ opacity: 0, scale: 0.7 }}
              transition={{ duration: 0.15 }}
            >
              <Check className="h-3.5 w-3.5 text-emerald-400" aria-hidden />
            </motion.span>
          ) : (
            <motion.span
              key="download"
              initial={{ opacity: 0, scale: 0.7 }}
              animate={{ opacity: 1, scale: 1 }}
              exit={{ opacity: 0, scale: 0.7 }}
              transition={{ duration: 0.15 }}
            >
              <Download className="h-3.5 w-3.5" aria-hidden />
            </motion.span>
          )}
        </AnimatePresence>
        <span>Export</span>
      </button>

      {/* ---- Popover ---- */}
      <AnimatePresence>
        {open && (
          <motion.div
            role="menu"
            aria-label="Export options"
            initial={{ opacity: 0, scale: 0.95, y: -4 }}
            animate={{ opacity: 1, scale: 1, y: 0 }}
            exit={{ opacity: 0, scale: 0.95, y: -4 }}
            transition={{ duration: 0.12, ease: 'easeOut' }}
            className={[
              'absolute right-0 top-[calc(100%+6px)] z-50',
              'w-56 rounded-xl border p-1.5',
              'border-[rgba(255,255,255,0.06)] bg-[rgba(8,10,18,0.88)]',
              'shadow-[0_8px_32px_rgba(0,0,0,0.6)] backdrop-blur-xl',
            ].join(' ')}
          >
            {/* Section label */}
            <p className="px-3 pb-1 pt-0.5 text-[9px] font-mono uppercase tracking-[0.18em] text-zinc-600">
              Export as
            </p>

            <OptionRow
              icon={<FileJson className="h-3.5 w-3.5" />}
              label="JSON"
              description="Raw session data via API"
              onClick={() => void handleExportJson()}
              disabled={!hasSession}
            />
            <OptionRow
              icon={<FileText className="h-3.5 w-3.5" />}
              label="Markdown"
              description="Structured mission report"
              onClick={handleExportMarkdown}
            />

            {/* Divider */}
            <div className="my-1 h-px bg-white/[0.05]" role="separator" />

            <OptionRow
              icon={<Link2 className="h-3.5 w-3.5" />}
              label="Share link"
              description="Copy decomp view URL"
              onClick={() => void handleShareLink()}
              disabled={!hasSession}
            />
          </motion.div>
        )}
      </AnimatePresence>

      {/* ---- Toast ---- */}
      <AnimatePresence>
        {toastMessage && (
          <motion.div
            key="toast"
            initial={{ opacity: 0, y: 4 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: 4 }}
            transition={{ duration: 0.15 }}
            role="status"
            aria-live="polite"
            className={[
              'absolute right-0 top-[calc(100%+44px)] z-50',
              'whitespace-nowrap rounded-lg border px-3 py-1.5',
              'border-[rgba(255,255,255,0.06)] bg-[rgba(8,10,18,0.92)]',
              'text-[11px] text-zinc-300 shadow-lg backdrop-blur-xl',
            ].join(' ')}
          >
            {toastMessage}
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}
